import 'dart:ui';

/// Render-only snapshot. Coordinates are table-space metres, x right/y down.
/// An engine adapter converts its units before publishing a frame.
class PracticeFrame {
  PracticeFrame({
    required Iterable<PracticeBall> balls,
    required Iterable<Iterable<Offset>> trajectories,
    required this.shot,
    required this.moving,
  }) : balls = List.unmodifiable(balls),
       trajectories = List.unmodifiable(
         trajectories.map((path) => List<Offset>.unmodifiable(path)),
       );
  final List<PracticeBall> balls;

  /// One polyline per predicted ball path; generated by the active simulator.
  final List<List<Offset>> trajectories;
  final PracticeShot shot;
  final bool moving;
}

class PracticeBall {
  const PracticeBall(this.number, this.position, {this.pocketed = false});
  final int number;
  final Offset position;
  final bool pocketed;
}

class PracticeShot {
  const PracticeShot({
    required this.directionRadians,
    required this.power,
    required this.spin,
    required this.elevationDegrees,
  });
  final double directionRadians;

  /// Normalized 0..1 power; spin in a unit disc, positive y = low cue.
  final double power;
  final Offset spin;
  final double elevationDegrees;
}
